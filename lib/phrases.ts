export function tierFor(percent: number): string {
  if (percent >= 100) return "complete";
  if (percent >= 75) return "high";
  if (percent >= 50) return "medium";
  if (percent >= 25) return "low";
  if (percent >= 1) return "veryLow";
  return "zero";
}

export function randomPhrase(percent: number): string {
  const arr = PHRASES[tierFor(percent)];
  return arr[Math.floor(Math.random() * arr.length)];
}
